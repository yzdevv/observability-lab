// Experiment 2 report: none vs cache-miss at 10/25/50 req/s. Usage: node analyse.ts <results-dir>
import { join } from 'node:path';
import { analyseWindow } from '../../scripts/lib/stats.ts';
import { dockerPeaks, exists, loadSummary, saveTrace, writeReport } from '../../scripts/lib/report.ts';
import { fmt, promValue, toSec } from '../../scripts/lib/sources.ts';

const dir = process.argv[2];
if (!dir) throw new Error('usage: node analyse.ts <results-dir>');

const md = ['# Experiment 2 — cache efficiency: results', '', `Source: \`${dir}\`. Generated by \`analyse.ts\`.`, '',
  'Latency from k6 (client side). DB queries/s = Postgres operations of the order API (`db.client.operation.duration` count) ' +
  'over the last 30 s of each step. SELECT in = share of traces whose `product.lookup` queried Postgres.', ''];
const rows: Record<string, unknown>[] = [];
const waterfalls: string[] = [];

for (const impl of ['node', 'go']) {
  md.push(`## ${impl}`, '', '| Req/s | Scenario | Accepted/s | p50 | p95 | p99 | DB queries/s | DB queries per request | SELECT in | product.lookup p50 | Errors |',
    '|---|---|---|---|---|---|---|---|---|---|---|');
  const runs: Record<string, Awaited<ReturnType<typeof loadSummary>>> = {};
  for (const scenario of ['none', 'cache-miss']) {
    const runDir = join(dir, `${impl}-${scenario}`);
    if (exists(runDir)) runs[scenario] = await loadSummary(runDir);
  }
  const stepNames = runs.none?.steps.map((s) => s.step) ?? [];
  for (const stepName of stepNames) {
    for (const scenario of ['none', 'cache-miss']) {
      const step = runs[scenario]?.steps.find((s) => s.step === stepName);
      if (!step) continue;
      const stats = await analyseWindow({ impl, scenario, from: step.from, to: step.to, sample: 300 });
      const select = stats.spans.find((s) => s.service === `order-api-${impl}` && /SELECT/.test(s.span));
      const lookup = stats.spans.find((s) => s.service === `order-api-${impl}` && s.span === 'product.lookup');
      const dbOps = await promValue(`sum(rate(db_client_operation_duration_seconds_count{service_name="order-api-${impl}"}[30s]))`, toSec(step.to));
      const acceptedPerS = step.accepted / Number.parseInt(step.duration);
      const errors = step.requests - step.accepted;
      md.push(`| ${step.targetRate} | ${scenario} | ${fmt(acceptedPerS)} | ${fmt(step.latencyMs.p50)} | ${fmt(step.latencyMs.p95)} | ` +
        `${fmt(step.latencyMs.p99)} | ${fmt(dbOps)} | ${fmt(dbOps !== null ? dbOps / acceptedPerS : null, 2)} | ` +
        `${select ? Math.round((select.traces / Math.max(stats.tracesSampled, 1)) * 100) : 0}% | ${fmt(lookup?.totalP50, 2)} ms | ${errors} |`);
      rows.push({ impl, scenario, step, dbOpsPerS: dbOps, selectShare: select ? select.traces / stats.tracesSampled : 0, lookup, typical: stats.typical });
      if (step.targetRate === 50) {
        const wf = await saveTrace(dir, `${impl}-${scenario}-50rps-typical`, stats.typical.traceId, step);
        if (wf) waterfalls.push(wf);
      }
    }
  }
  for (const scenario of ['none', 'cache-miss']) {
    const peaks = await dockerPeaks(join(dir, `${impl}-${scenario}`));
    md.push('', `Peak during ${scenario}: postgres ${fmt(peaks.postgres?.cpu, 0)}% CPU, order-api-${impl} ${fmt(peaks[`order-api-${impl}`]?.cpu, 0)}% CPU, redis ${fmt(peaks.redis?.cpu, 0)}% CPU (docker stats, 100% = one core).`);
  }
  md.push('');
}
md.push('## Typical traces at 50 req/s', '', '```', waterfalls.join('\n\n'), '```');
await writeReport(dir, md, rows);
