// Experiment 3 report: worker-retry vs none at 5 req/s. Usage: node analyse.ts <results-dir>
import { join } from 'node:path';
import { analyseWindow } from '../../scripts/lib/stats.ts';
import { exists, loadSummary, saveTrace, writeReport } from '../../scripts/lib/report.ts';
import { fmt, lokiQuery, sql, toSec } from '../../scripts/lib/sources.ts';

const dir = process.argv[2];
if (!dir) throw new Error('usage: node analyse.ts <results-dir>');

const md = ['# Experiment 3 — worker retry: results', '', `Source: \`${dir}\`. Generated by \`analyse.ts\`.`, '',
  'Time to complete = `processed_at − created_at` from Postgres for the orders created in the measured window. ' +
  'Retry log lines = worker lines "retry scheduled" in Loki from the window start to 3 s after its end ' +
  '(the last retries finish within ~2 s; the next run starts ~7 s later). Expect 2 per worker-retry order.', '',
  '| Impl | Scenario | Orders | Completed | Failed | Attempts per order | Complete p50 | Complete p95 | Complete max | Retry log lines | Per order | API p95 |',
  '|---|---|---|---|---|---|---|---|---|---|---|---|'];
const rows: Record<string, unknown>[] = [];
const waterfalls: string[] = [];

for (const impl of ['node', 'go']) {
  for (const scenario of ['none', 'worker-retry']) {
    const runDir = join(dir, `${impl}-${scenario}`);
    if (!exists(runDir)) continue;
    const step = (await loadSummary(runDir)).steps[0]!;
    const [db] = sql(`SELECT count(*) AS orders,
        count(*) FILTER (WHERE status = 'completed') AS completed,
        count(*) FILTER (WHERE status = 'failed') AS failed,
        round(avg(attempts), 2) AS attempts,
        round(percentile_cont(0.5) WITHIN GROUP (ORDER BY extract(epoch FROM processed_at - created_at) * 1000)::numeric, 0) AS p50,
        round(percentile_cont(0.95) WITHIN GROUP (ORDER BY extract(epoch FROM processed_at - created_at) * 1000)::numeric, 0) AS p95,
        round(max(extract(epoch FROM processed_at - created_at) * 1000)::numeric, 0) AS max
      FROM orders WHERE impl = '${impl}' AND scenario = '${scenario}'
        AND created_at BETWEEN '${step.from}' AND '${step.to}'`);
    const end = toSec(step.to) + 3;
    const retryLogs = (await lokiQuery(`{service_name="worker-${impl}"} |= "retry scheduled"`, toSec(step.from), end)).length;
    md.push(`| ${impl} | ${scenario} | ${db?.orders} | ${db?.completed} | ${db?.failed} | ${db?.attempts} | ${db?.p50} ms | ${db?.p95} ms | ` +
      `${db?.max} ms | ${retryLogs} | ${fmt(retryLogs / Math.max(Number(db?.orders ?? 0), 1), 2)} | ${fmt(step.latencyMs.p95)} ms |`);
    rows.push({ impl, scenario, step, db, retryLogs });
    if (scenario === 'worker-retry') {
      const stats = await analyseWindow({ impl, scenario, from: step.from, to: step.to, sample: 50 });
      const wf = await saveTrace(dir, `${impl}-worker-retry-typical`, stats.typical.traceId, step);
      if (wf) waterfalls.push(wf);
    }
  }
}
md.push('', '## Typical worker-retry traces', '', '```', waterfalls.join('\n\n'), '```');
await writeReport(dir, md, rows);
