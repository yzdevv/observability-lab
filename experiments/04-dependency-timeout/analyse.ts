// Experiment 4 report: dependency timeout with and without the circuit breaker.
// Usage: node analyse.ts <results-dir>
import { join } from 'node:path';
import { exists, findTrace, loadSummary, saveTrace, statusText, writeReport, type StepStats } from '../../scripts/lib/report.ts';
import { fmt, lokiQuery, promQuery, promValue, toSec } from '../../scripts/lib/sources.ts';

const dir = process.argv[2];
if (!dir) throw new Error('usage: node analyse.ts <results-dir>');
const CYCLE = 60;
const OUTAGE = 30;

const md = ['# Experiment 4 — dependency timeout and circuit breaker: results', '', `Source: \`${dir}\`. Generated by \`analyse.ts\`.`, '',
  'Traffic: 10 req/s normal orders + 40 req/s `dependency-timeout` for 180 s through the gateway (in-flight limit 20). ' +
  'The degraded payment provider is down for the first 30 s of every minute. Requests are split by whether they were sent during the outage.', ''];
const rows: Record<string, unknown>[] = [];
const waterfalls: string[] = [];
const cell = (s: StepStats | undefined) => s ? `${s.requests} | ${fmt(s.latencyMs.p50)} | ${fmt(s.latencyMs.p95)} | ${statusText(s.status)}` : '– | – | – | –';

for (const impl of ['node', 'go']) {
  md.push(`## ${impl}`, '');
  md.push('| Breaker | Traffic | Window | Requests | p50 ms | p95 ms | Responses |', '|---|---|---|---|---|---|---|');
  const extra: string[] = [];
  for (const breaker of ['on', 'off']) {
    const runDir = join(dir, `${impl}-breaker-${breaker}`);
    if (!exists(runDir)) continue;
    const summary = await loadSummary(runDir);
    for (const step of summary.steps) {
      for (const w of ['outage', 'healthy']) {
        md.push(`| ${breaker} | ${step.scenario} | ${w} | ${cell(step.byWindow?.[w])} |`);
      }
    }
    const first = summary.steps[0]!;
    const from = toSec(first.from);
    const to = toSec(first.to);
    const range = `${Math.round(to - from)}s`;
    const inflightMax = await promValue(`max_over_time(lab_gateway_inflight[${range}])`, to);
    const shed = await promQuery(`sum by (lab_shed_reason) (increase(lab_gateway_shed_total{lab_impl="${impl}"}[${range}]))`, to);
    const shedText = shed.map((s) => `${s.metric.lab_shed_reason ?? '?'} ${Math.round(Number(s.value[1]))}`).join(', ') || 'none';
    // Breaker transitions for the degraded endpoint, from the API's logs.
    const logs = await lokiQuery(`{service_name="order-api-${impl}"} |= "circuit breaker" | dependency="payment-degraded"`, from, to + 5);
    const transitions = logs.map((l) => ({ ts: l.ts, to: /circuit breaker ([a-z-]+)/.exec(l.line)?.[1] ?? '?' }));
    // Recovery: from the end of each outage window to the breaker closing again.
    const recoveries: number[] = [];
    const openings: number[] = [];
    for (let c = Math.ceil(from / CYCLE) * CYCLE; c < to; c += CYCLE) {
      const opened = transitions.find((t) => t.to === 'open' && t.ts >= c && t.ts < c + OUTAGE);
      if (opened) openings.push(opened.ts - c);
      const closed = transitions.find((t) => t.to === 'closed' && t.ts >= c + OUTAGE && t.ts < c + CYCLE);
      if (closed && c + OUTAGE < to) recoveries.push(closed.ts - (c + OUTAGE));
    }
    extra.push(`- Breaker ${breaker}: peak in-flight at the gateway ${fmt(inflightMax, 0)} (limit 20); refused by guards: ${shedText}; ` +
      `breaker transitions ${transitions.length}` +
      (openings.length ? `; opened ${openings.map((s) => fmt(s, 1) + ' s').join(', ')} after an outage began` : '') +
      (recoveries.length ? `; closed ${recoveries.map((s) => fmt(s, 1) + ' s').join(', ')} after an outage ended` : '') + '.');
    rows.push({ impl, breaker, steps: summary.steps, inflightMax, shed, transitions, openings, recoveries });

    if (breaker === 'on') {
      const around = { from: first.from, to: first.to };
      const open = await findTrace(`{ resource.service.name = "order-api-${impl}" && span.lab.breaker.rejected = true }`, around);
      const timeout = await findTrace(`{ resource.service.name = "order-api-${impl}" && name = "payment.authorize" && status = error && span.lab.breaker.rejected != true }`, around);
      for (const [label, id] of [[`${impl}-timeout`, timeout], [`${impl}-circuit-open`, open]] as const) {
        const wf = await saveTrace(dir, label, id, around);
        if (wf) waterfalls.push(wf);
      }
    }
  }
  md.push('', ...extra, '');
}
md.push('## Example traces (breaker on)', '', '```', waterfalls.join('\n\n'), '```');
await writeReport(dir, md, rows);
