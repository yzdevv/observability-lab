// Turn a results directory from run.sh into report.md + report.json, and save example traces
// (Tempo keeps traces for 48 h; the saved copies feed the write-up and the offline demo).
// Usage: node experiments/01-slow-db/analyse.ts <results-dir>
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { analyseWindow, type WindowStats } from '../../scripts/lib/stats.ts';
import { getTrace } from '../../scripts/lib/tempo.ts';
import { renderWaterfall } from '../../scripts/lib/waterfall.ts';

type Step = {
  step: string;
  targetRate: number;
  from: string;
  to: string;
  requests: number;
  throughput: number;
  accepted: number;
  status: Record<string, number>;
  errorRate: number | null;
  latencyMs: { avg: number; p50: number; p90: number; p95: number; p99: number; max: number };
};
type Summary = { impl: string; scenario: string; steps: Step[] };
type DockerSample = { name: string; at: string; cpu: string; mem: string };

const dir = process.argv[2];
if (!dir) {
  console.error('usage: node experiments/01-slow-db/analyse.ts <results-dir>');
  process.exit(2);
}

const IMPLS = ['node', 'go'] as const;
const SCENARIOS = ['none', 'slow-db'] as const;
const POOL_WAIT = { node: 'pg-pool.connect', go: 'pool.acquire' } as const;
const fmt = (n: number | null | undefined, digits = 1) => (n === null || n === undefined ? '–' : n.toFixed(digits));

const readJson = async <T>(p: string) => JSON.parse(await readFile(p, 'utf8')) as T;

async function dockerPeaks(runDir: string) {
  const file = join(runDir, 'docker-stats.jsonl');
  if (!existsSync(file)) return {};
  const peaks: Record<string, { cpu: number; memMiB: number }> = {};
  for (const line of (await readFile(file, 'utf8')).split('\n')) {
    if (!line.trim()) continue;
    const s = JSON.parse(line) as DockerSample;
    const name = s.name.replace(/^observability-lab-/, '').replace(/-1$/, '');
    const cpu = Number.parseFloat(s.cpu);
    const [used = '0'] = s.mem.split(' / ');
    const memMiB = Number.parseFloat(used) * (used.endsWith('GiB') ? 1024 : used.endsWith('KiB') ? 1 / 1024 : 1);
    const p = (peaks[name] ??= { cpu: 0, memMiB: 0 });
    p.cpu = Math.max(p.cpu, cpu);
    p.memMiB = Math.max(p.memMiB, memMiB);
  }
  return peaks;
}

const poolWait = (stats: WindowStats, impl: (typeof IMPLS)[number]) =>
  stats.spans.find((s) => !s.async && s.service === `order-api-${impl}` && s.span === POOL_WAIT[impl]);

const tracesDir = join(dir, 'traces');
await mkdir(tracesDir, { recursive: true });
async function saveTrace(label: string, traceId: string, around: { from: string; to: string }) {
  const window = { startSec: Date.parse(around.from) / 1000 - 60, endSec: Date.parse(around.to) / 1000 + 60 };
  const spans = traceId ? await getTrace(traceId, window) : undefined;
  if (!spans) return undefined;
  await writeFile(join(tracesDir, `${label}.json`), JSON.stringify({ traceId, spans }, null, 1) + '\n');
  return renderWaterfall(spans, { title: `${label} (trace ${traceId})` });
}

const md: string[] = [`# Experiment 1 — slow database: results`, '', `Source: \`${dir}\`. Generated by \`analyse.ts\`.`, ''];
const report: Record<string, unknown> = {};

// ---------- Part A: baseline vs degraded ----------
const partA = join(dir, 'a');
if (existsSync(partA)) {
  md.push('## Part A — baseline vs slow-db at 4 req/s', '');
  md.push('Client latency is measured by k6; the median run (by p95) of 3 is shown, with the p95 range across runs.',
    'Culprit = request-path span with the most self time at the median trace, found from Tempo alone.', '');
  md.push('| Impl | Scenario | p50 | p95 | p99 | p95 range (3 runs) | Errors | Culprit span | Self p50 | Share | Traces |');
  md.push('|---|---|---|---|---|---|---|---|---|---|---|');
  const rows: Record<string, unknown>[] = [];
  const waterfalls: string[] = [];
  const runs = await readdir(partA);
  for (const impl of IMPLS) {
    for (const scenario of SCENARIOS) {
      const mine = runs.filter((r) => r.endsWith(`-${impl}-${scenario}`)).sort();
      const loaded = await Promise.all(
        mine.map(async (r) => ({ run: r, summary: await readJson<Summary>(join(partA, r, 'summary.json')) })),
      );
      if (!loaded.length) continue;
      const byP95 = [...loaded].sort((a, b) => a.summary.steps[0]!.latencyMs.p95 - b.summary.steps[0]!.latencyMs.p95);
      const median = byP95[Math.floor((byP95.length - 1) / 2)]!;
      const step = median.summary.steps[0]!;
      const stats = await analyseWindow({ impl, scenario, from: step.from, to: step.to });
      const p95s = byP95.map((r) => r.summary.steps[0]!.latencyMs.p95);
      const errors = loaded.reduce((n, r) => n + (r.summary.steps[0]!.requests - r.summary.steps[0]!.accepted), 0);
      const total = loaded.reduce((n, r) => n + r.summary.steps[0]!.requests, 0);
      const c = stats.culprit;
      md.push(`| ${impl} | ${scenario} | ${fmt(step.latencyMs.p50)} | ${fmt(step.latencyMs.p95)} | ${fmt(step.latencyMs.p99)} | ` +
        `${fmt(p95s[0])}–${fmt(p95s.at(-1))} | ${errors}/${total} | \`${c?.span ?? '?'}\` (${c?.service ?? '?'}) | ` +
        `${fmt(c?.selfP50)} | ${c ? Math.round((c.selfP50 / stats.request.p50) * 100) : 0}% | ${stats.tracesSampled}/${stats.tracesFound} |`);
      rows.push({ impl, scenario, medianRun: median.run, k6: step, p95AcrossRuns: p95s, errors, total, traces: stats });
      const wf = await saveTrace(`a-${impl}-${scenario}-typical`, stats.typical.traceId, step);
      if (wf) waterfalls.push(wf);
    }
  }
  report.partA = rows;

  // Degradation per implementation.
  md.push('', '| Impl | Δ p50 (slow-db − none) | Δ p95 |', '|---|---|---|');
  for (const impl of IMPLS) {
    const get = (s: string) => rows.find((r) => r.impl === impl && r.scenario === s)?.k6 as Step | undefined;
    const base = get('none');
    const slow = get('slow-db');
    if (base && slow) {
      md.push(`| ${impl} | +${fmt(slow.latencyMs.p50 - base.latencyMs.p50)} ms | +${fmt(slow.latencyMs.p95 - base.latencyMs.p95)} ms |`);
    }
  }
  md.push('', '### Typical traces (closest to the median)', '', '```', waterfalls.join('\n\n'), '```', '');
}

// ---------- Part B: rising load ----------
const partB = join(dir, 'b');
if (existsSync(partB)) {
  md.push('## Part B — rising load, 10 → 50 req/s', '');
  md.push('Each step runs 30 s. Pool wait = self time of the connection-pool span (`pg-pool.connect` in Node, ' +
    '`pool.acquire` in Go). 503s come from the gateway in-flight guard (max 20 requests).', '');
  const rows: Record<string, unknown>[] = [];
  const waterfalls: string[] = [];
  for (const impl of IMPLS) {
    for (const scenario of SCENARIOS) {
      const runDir = join(partB, `${impl}-${scenario}`);
      if (!existsSync(runDir)) continue;
      const summary = await readJson<Summary>(join(runDir, 'summary.json'));
      const peaks = await dockerPeaks(runDir);
      md.push(`### ${impl} / ${scenario}`, '');
      md.push('| Target req/s | Accepted/s | p50 | p95 | p99 | 503 | Other errors | Pool wait p50 | Pool wait p95 | Culprit (self p50) |');
      md.push('|---|---|---|---|---|---|---|---|---|---|');
      for (const step of summary.steps) {
        const stats = await analyseWindow({ impl, scenario, from: step.from, to: step.to });
        const wait = poolWait(stats, impl);
        const other = step.requests - step.accepted - (step.status['503'] ?? 0);
        const c = stats.culprit;
        md.push(`| ${step.targetRate} | ${fmt(step.accepted / 30)} | ${fmt(step.latencyMs.p50)} | ${fmt(step.latencyMs.p95)} | ` +
          `${fmt(step.latencyMs.p99)} | ${step.status['503'] ?? 0} | ${other} | ${fmt(wait?.selfP50)} | ${fmt(wait?.selfP95)} | ` +
          `\`${c?.span ?? '?'}\` ${fmt(c?.selfP50)} |`);
        rows.push({ impl, scenario, step, poolWait: wait, culprit: c, typical: stats.typical, slowest: stats.slowest });
        if (scenario === 'slow-db' && step.targetRate === 50) {
          const wf = await saveTrace(`b-${impl}-slow-db-50rps-slowest`, stats.slowest.traceId, step);
          if (wf) waterfalls.push(wf);
        }
      }
      const api = peaks[`order-api-${impl}`];
      const gw = peaks.gateway;
      const pg = peaks.postgres;
      md.push('', `Peak usage during the run: order-api-${impl} ${fmt(api?.cpu, 0)}% CPU / ${fmt(api?.memMiB, 0)} MiB, ` +
        `gateway ${fmt(gw?.cpu, 0)}% / ${fmt(gw?.memMiB, 0)} MiB, postgres ${fmt(pg?.cpu, 0)}% / ${fmt(pg?.memMiB, 0)} MiB ` +
        '(docker stats every 10 s; 100% = one core).', '');
    }
  }
  report.partB = rows;
  if (waterfalls.length) md.push('### Slowest slow-db trace at 50 req/s', '', '```', waterfalls.join('\n\n'), '```', '');
}

await writeFile(join(dir, 'report.md'), md.join('\n') + '\n');
await writeFile(join(dir, 'report.json'), JSON.stringify(report, null, 1) + '\n');
console.log(md.join('\n'));
