// Experiment 5 report: Node vs Go order API under rising load, called directly.
// Usage: node analyse.ts <results-dir>
import { join } from 'node:path';
import { exists, loadSummary, readJson, statusText, writeReport } from '../../scripts/lib/report.ts';
import { fmt, promValue, toSec } from '../../scripts/lib/sources.ts';

const dir = process.argv[2];
if (!dir) throw new Error('usage: node analyse.ts <results-dir>');

const md = ['# Experiment 5 — Node vs Go under load: results', '', `Source: \`${dir}\`. Generated by \`analyse.ts\`.`, '',
  'k6 → order API directly (no gateway), scenario `none`, 30 s per step. Both APIs: 0.5 CPU, 128 MiB, DB pool 10. ' +
  'Container numbers are from the services\' own cgroup metrics over the last 30 s of each step.', ''];
const rows: Record<string, unknown>[] = [];
const startup: string[] = [];

for (const impl of ['node', 'go']) {
  const runDir = join(dir, `${impl}-none`);
  if (!exists(runDir)) continue;
  const svc = `order-api-${impl}`;
  const summary = await loadSummary(runDir);
  md.push(`## ${impl}`, '', '| Target req/s | Accepted/s | p50 | p95 | p99 | Errors | CPU used (cores) | Throttled | Memory | ' +
    (impl === 'node' ? 'Event loop p99' : 'Goroutines') + ' | DB pool waiting |', '|---|---|---|---|---|---|---|---|---|---|---|');
  for (const step of summary.steps) {
    const at = toSec(step.to);
    const q = (e: string) => promValue(e, at);
    const cpu = await q(`rate(lab_cgroup_cpu_usage_time_seconds_total{service_name="${svc}"}[30s])`);
    const throttled = await q(`100 * rate(lab_cgroup_cpu_throttled_periods_total{service_name="${svc}"}[30s]) / rate(lab_cgroup_cpu_periods_total{service_name="${svc}"}[30s])`);
    const mem = await q(`max_over_time(lab_cgroup_memory_usage_bytes{service_name="${svc}"}[30s]) / 1048576`);
    const runtime = impl === 'node'
      ? await q(`max_over_time(nodejs_eventloop_delay_p99_seconds{service_name="${svc}"}[30s]) * 1000`)
      : await q(`max_over_time(go_goroutine_count{service_name="${svc}"}[30s])`);
    const poolWait = impl === 'node'
      ? await q(`max_over_time(db_client_connection_pending_requests{service_name="${svc}"}[30s])`)
      : await q(`rate(pgxpool_empty_acquire_total{service_name="${svc}"}[30s])`);
    const accepted = step.accepted / Number.parseInt(step.duration);
    const errors = step.requests - step.accepted;
    md.push(`| ${step.targetRate} | ${fmt(accepted)} | ${fmt(step.latencyMs.p50)} | ${fmt(step.latencyMs.p95)} | ${fmt(step.latencyMs.p99)} | ` +
      `${errors ? statusText(Object.fromEntries(Object.entries(step.status).filter(([c]) => c !== '202'))) : 0} | ${fmt(cpu, 2)} | ${fmt(throttled, 0)}% | ` +
      `${fmt(mem, 0)} MiB | ${impl === 'node' ? (runtime !== null && runtime < 1000 ? fmt(runtime, 0) + ' ms' : '–') : fmt(runtime, 0)} | ${impl === 'node' ? fmt(poolWait, 0) + ' max' : fmt(poolWait, 1) + '/s'} |`);
    rows.push({ impl, step, cpu, throttled, mem, runtime, poolWait });
  }
  md.push('');
  const startFile = join(dir, `${impl}-startup.json`);
  if (exists(startFile)) {
    const s = await readJson<{ startToListeningS: number; imageBytes: number }>(startFile);
    startup.push(`| ${impl} | ${fmt(s.startToListeningS * 1000, 0)} ms | ${fmt(s.imageBytes / 1e6, 0)} MB |`);
  }
}
md.push('Node event-loop delay is "–" for runs made while the runtime instrumentation sampled every 5 s: each reading then ' +
  'included the 5 s interval and was meaningless (fixed to 10 ms afterwards).', '');
md.push('## Start-up and image', '', '| Impl | Container start → listening | Image size |', '|---|---|---|', ...startup,
  '', 'From Docker\'s container start time to the app\'s "listening" log line (includes telemetry setup and DB/Redis clients).');
await writeReport(dir, md, rows);
