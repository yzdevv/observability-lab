// Experiment 6 report: CPU per request under four telemetry settings, median of the rounds.
// Usage: node analyse.ts <results-dir>
import { readdir } from 'node:fs/promises';
import { join } from 'node:path';
import { percentile } from '../../scripts/lib/stats.ts';
import { loadSummary, readJson, writeReport } from '../../scripts/lib/report.ts';
import { fmt, promValue, toSec } from '../../scripts/lib/sources.ts';

const dir = process.argv[2];
if (!dir) throw new Error('usage: node analyse.ts <results-dir>');
type Cpu = { at: string; cpuSeconds: Record<string, number> } | null;
type Meta = { containerCpuBefore: Cpu; containerCpuAfter: Cpu };

const median = (xs: (number | null)[]) => {
  const v = xs.filter((x): x is number => x !== null);
  return v.length ? percentile(v, 50) : null;
};
const range = (xs: number[]) => `${fmt(Math.min(...xs), 1)}–${fmt(Math.max(...xs), 1)}`;

const md = ['# Experiment 6 — the cost of telemetry: results', '', `Source: \`${dir}\`. Generated by \`analyse.ts\`.`, '',
  'Same traffic in every run: 40 req/s, scenario `none`, 40 s, through the gateway. CPU = cumulative CPU per container ' +
  'from the Docker Engine API before and after the k6 run, divided by the requests sent (so it includes background work ' +
  'such as metric export). Traces are on in every setting. Each cell is the median of the rounds; the app-total range ' +
  'shows the spread between rounds.', '',
  '| Setting | Impl | gateway | order API | worker | fake-payment | App total (range) | collector | Loki | Tempo | Prometheus | Gateway throttled | p50 | p95 | p99 | Non-202 |',
  '|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|'];
const rows: Record<string, unknown>[] = [];

for (const variant of (await readdir(dir)).filter((d) => /^\d-/.test(d)).sort()) {
  const runs = await readdir(join(dir, variant));
  for (const impl of ['node', 'go']) {
    const mine = runs.filter((r) => r.endsWith(`-${impl}`)).sort();
    const per: Record<string, (number | null)[]> = {};
    const add = (k: string, v: number | null) => (per[k] ??= []).push(v);
    const appTotals: number[] = [];
    for (const r of mine) {
      const runDir = join(dir, variant, r);
      const step = (await loadSummary(runDir)).steps[0]!;
      const meta = await readJson<Meta>(join(runDir, 'meta.json'));
      const before = meta.containerCpuBefore?.cpuSeconds ?? {};
      const after = meta.containerCpuAfter?.cpuSeconds ?? {};
      const perReq = (svc: string) => after[svc] !== undefined && before[svc] !== undefined
        ? ((after[svc]! - before[svc]!) / Math.max(step.requests, 1)) * 1000 : null;
      const svcs = { gateway: 'gateway', api: `order-api-${impl}`, worker: `worker-${impl}`, payment: 'fake-payment',
        collector: 'otel-collector', loki: 'loki', tempo: 'tempo', prometheus: 'prometheus' };
      let app = 0;
      for (const [k, name] of Object.entries(svcs)) {
        const v = perReq(name);
        add(k, v);
        if (['gateway', 'api', 'worker', 'payment'].includes(k)) app += v ?? 0;
      }
      appTotals.push(app);
      add('app', app);
      add('p50', step.latencyMs.p50);
      add('p95', step.latencyMs.p95);
      add('p99', step.latencyMs.p99);
      add('non202', step.requests - step.accepted);
      // Throttling needs the services' own metrics, so it is missing for traces-only.
      add('throttled', await promValue(
        `100 * sum(increase(lab_cgroup_cpu_throttled_periods_total{service_name="gateway"}[40s])) / sum(increase(lab_cgroup_cpu_periods_total{service_name="gateway"}[40s]))`,
        toSec(step.to)));
    }
    if (!mine.length) continue;
    const m = (k: string) => median(per[k] ?? []);
    md.push(`| ${variant.replace(/^\d-/, '')} | ${impl} | ${fmt(m('gateway'), 2)} | ${fmt(m('api'), 2)} | ${fmt(m('worker'), 2)} | ${fmt(m('payment'), 2)} | ` +
      `**${fmt(m('app'), 1)}** (${range(appTotals)}) | ${fmt(m('collector'), 2)} | ${fmt(m('loki'), 2)} | ${fmt(m('tempo'), 2)} | ${fmt(m('prometheus'), 2)} | ` +
      `${m('throttled') === null ? '–' : fmt(m('throttled'), 0) + '%'} | ${fmt(m('p50'))} | ${fmt(m('p95'))} | ${fmt(m('p99'))} | ${fmt(m('non202'), 0)} |`);
    rows.push({ variant, impl, runs: mine.length, medians: Object.fromEntries(Object.keys(per).map((k) => [k, m(k)])), appTotals });
  }
}
md.push('', 'CPU columns: milliseconds of CPU per request. "Gateway throttled" = share of 100 ms scheduling periods in which the ' +
  'gateway hit its CPU quota. Non-202 = requests refused (mostly 503 from the in-flight guard) out of ~1600 per run.');
await writeReport(dir, md, rows);
